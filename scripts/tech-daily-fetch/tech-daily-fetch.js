// 生成日报内容
function generateDailyReport(news, date) {
  let md = `# 📰 AI/科技日报 - ${date}\n\n`;
  
  // 热门资讯
  md += `## 🔥 热门资讯\n\n`;
  news.forEach((item, idx) => {
    md += `### ${idx + 1}. [${item.title}](${item.link})\n`;
    md += `来源：${item.source} | 标签：${item.tags.join(' ')}\n`;
    md += `${item.summary}\n\n`;
  });
  
  // GitHub Trending（模拟）
  md += `## 📈 GitHub Trending\n\n`;
  md += `1. [langchain-ai/langchain](https://github.com/langchain-ai/langchain) - LLM 应用开发框架\n`;
  md += `2. [openai/openai-python](https://github.com/openai/openai-python) - OpenAI Python 库\n`;
  md += `3. [anthropics/claude-sdk](https://github.com/anthropics/claude-sdk) - Claude SDK\n\n`;
  
  // 底部
  md += `---\n`;
  md += `_Generated by AI Tech Daily | 数据来源：${config.sources.map(s => s.name).join(', ')}_\n`;
  
  return md;
}

